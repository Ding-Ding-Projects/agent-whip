// Refuses to let a private term reach a public file.
//
// The awkward part of a guard like this is that the list of things it must catch is itself the
// secret. A public repository carrying the list would be the leak, performed by the check written
// to prevent it. So this file carries no terms — only salted SHA-256 digests, which cannot be read
// backwards, and it recomputes candidate digests from the files it scans.
//
// How it works: every tracked text file is lowercased and reduced to word n-grams of length 1..4.
// Each n-gram is hashed with the same salt and looked up in the digest set. A hit names the file
// and the offset but NEVER prints the matched text, because printing it in CI output would leak it
// just as thoroughly as committing it.
//
// The digest set is generated by `npm run reserved:lock`, which reads a private term list from a
// path given by AGENT_WHIP_RESERVED_TERMS. That file is not in this repository and must not be.
//
// Fail open for a stranger, closed for staleness. Someone who has no private list is skipped with
// a printed reason — refusing an outsider a build of a public repository would be absurd. What is
// refused is a digest set that is present and does not match, which is the state that means
// something is actually wrong.
import { createHash } from 'node:crypto';
import { readFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const LOCK = new URL('./reserved-terms.lock.json', import.meta.url);

if (!existsSync(LOCK)) {
  console.log('check-reserved-terms: SKIP — no reserved-terms.lock.json present.');
  console.log('  This is expected outside the maintainer environment. Nothing is enforced.');
  process.exit(0);
}

const lock = JSON.parse(readFileSync(LOCK, 'utf8'));
if (lock.version !== 1 || !Array.isArray(lock.digests) || typeof lock.salt !== 'string') {
  console.error('check-reserved-terms: FAIL — lock file is present but malformed.');
  console.error('  A malformed lock is treated as a failure, never as an absent one: a guard that');
  console.error('  silently stops guarding is worse than no guard at all.');
  process.exit(1);
}

const digests = new Set(lock.digests);
const salt = lock.salt;
const hash = (s) => createHash('sha256').update(salt).update(' ').update(s).digest('hex').slice(0, 32);

// Verify this checker's hash agrees with the generator's before trusting a single result. The
// two live in separate files and have drifted once already — the separator here was a NUL byte
// rather than a space, so every digest missed and the guard reported PASS on a planted term. A
// mismatch here is a hard failure, never a skip: a guard that cannot match is not a guard.
if (typeof lock.canary === 'string' && typeof lock.canaryInput === 'string') {
  if (hash(lock.canaryInput) !== lock.canary) {
    console.error('check-reserved-terms: FAIL — hash canary mismatch.');
    console.error('  This checker and the lock generator no longer compute the same digest, so every');
    console.error('  comparison below would silently miss. Regenerate the lock, or diff the hash');
    console.error('  function in this file against scripts/make-reserved-lock.mjs.');
    process.exit(1);
  }
} else {
  console.error('check-reserved-terms: FAIL — lock predates the hash canary. Regenerate it.');
  process.exit(1);
}

const TEXT = /\.(md|markdown|ts|tsx|js|mjs|cjs|json|ya?ml|html|css|txt|bat|sh)$/i;
const files = execSync('git ls-files', { encoding: 'utf8' })
  .trim().split('\n').filter((f) => f && TEXT.test(f));

let violations = 0;
let scanned = 0;

for (const file of files) {
  let text;
  try {
    text = readFileSync(file, 'utf8');
  } catch {
    continue;
  }
  scanned++;
  // Split into words, keeping a line number for each so a hit can be located without quoting it.
  const lines = text.split(/\r?\n/);
  for (let ln = 0; ln < lines.length; ln++) {
    const words = lines[ln].toLowerCase().match(/[a-z0-9一-鿿]+/g);
    if (!words) continue;
    for (let i = 0; i < words.length; i++) {
      for (let n = 1; n <= 4 && i + n <= words.length; n++) {
        if (digests.has(hash(words.slice(i, i + n).join(' ')))) {
          // Deliberately does not print the term. Naming it here would put it in CI logs.
          console.error(`check-reserved-terms: FAIL — ${file}:${ln + 1} contains a reserved term.`);
          violations++;
          n = 5; // stop extending this start position; one report per position is enough
        }
      }
    }
  }
}

if (violations > 0) {
  console.error(`check-reserved-terms: ${violations} violation(s) across ${scanned} file(s).`);
  console.error('  The offending text is intentionally not printed. Open the named line to see it.');
  process.exit(1);
}
console.log(`check-reserved-terms: PASS — ${scanned} file(s) scanned, ${digests.size} digest(s) enforced.`);
