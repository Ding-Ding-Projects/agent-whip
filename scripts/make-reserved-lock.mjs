// Generates scripts/reserved-terms.lock.json from a PRIVATE term list.
//
// Run as: AGENT_WHIP_RESERVED_TERMS=<path-to-private-list> node scripts/make-reserved-lock.mjs
//
// The input file is one term per line, blank lines and `#` comments ignored. It lives outside this
// repository and must stay there. What lands here is salted digests, which cannot be read back.
//
// The salt is random per generation and stored in the lock. That is deliberate and its limits are
// worth being honest about: a salt in the same file as the digests does not stop someone who
// already suspects a specific phrase from confirming it by hashing their guess. It stops bulk
// dictionary recovery, not targeted confirmation. The real protection is that the terms are
// unremarkable words to anyone who does not already know the scheme.
import { createHash, randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.env.AGENT_WHIP_RESERVED_TERMS;
if (!src) {
  console.error('make-reserved-lock: set AGENT_WHIP_RESERVED_TERMS to the private term list path.');
  console.error('  That file must NOT live inside this repository.');
  process.exit(2);
}

const raw = readFileSync(src, 'utf8');
const terms = raw
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.toLowerCase())
  // normalise to the same word-splitting the checker uses, so a term with punctuation still matches
  .map((l) => (l.match(/[a-z0-9一-鿿]+/g) || []).join(' '))
  .filter(Boolean);

if (terms.length === 0) {
  console.error('make-reserved-lock: the term list produced zero terms. Refusing to write an empty lock.');
  console.error('  An empty digest set would pass on everything, which is the failure this guard exists to prevent.');
  process.exit(1);
}

const tooLong = terms.filter((t) => t.split(' ').length > 4);
if (tooLong.length) {
  console.error(`make-reserved-lock: ${tooLong.length} term(s) are longer than the checker's 4-word n-gram window.`);
  console.error('  Those would never match. Shorten them or raise the window in check-reserved-terms.mjs.');
  process.exit(1);
}

const salt = randomBytes(16).toString('hex');
const hash = (s) => createHash('sha256').update(salt).update(' ').update(s).digest('hex').slice(0, 32);

// A canary over a deliberately public, non-secret string. The checker recomputes it and refuses
// to run if it disagrees. This exists because the separator in the checker's hash was once written
// as a NUL byte instead of a space: same salt, same terms, different digests, and a guard that
// matched nothing while printing PASS. A canary turns that silent drift into a loud failure.
const CANARY_INPUT = 'agent whip canary do not treat as secret';

const lock = {
  version: 1,
  salt,
  note: 'Salted digests of reserved terms. Generated by scripts/make-reserved-lock.mjs from a private list. No plaintext term appears here or anywhere in this repository.',
  digests: [...new Set(terms.map(hash))].sort(),
  canaryInput: CANARY_INPUT,
  canary: hash(CANARY_INPUT),
};

const out = new URL('./reserved-terms.lock.json', import.meta.url);
writeFileSync(out, JSON.stringify(lock, null, 2) + '\n', 'utf8');
console.log(`make-reserved-lock: wrote ${lock.digests.length} digest(s) from ${terms.length} term(s).`);
console.log('  No plaintext was written. Verify with: node scripts/check-reserved-terms.mjs');
